"""Generate C++ data from the vendored, unmodified MediaPipe connection table."""
import ast
import hashlib
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = (root / "vendor/face_mesh_connections.py").read_bytes()
assert hashlib.sha256(source).hexdigest() == "cc7171e44d0612db38720cb2fd2516c395992cdd7457efe341543be6f3c22d87"
tree = ast.parse(source.decode())
tables = {}
for statement in tree.body:
    if isinstance(statement, ast.Assign) and isinstance(statement.value, ast.Call):
        call = statement.value
        if isinstance(call.func, ast.Name) and call.func.id == "frozenset" and call.args:
            tables[statement.targets[0].id] = set(ast.literal_eval(call.args[0]))
names = ("FACEMESH_TESSELATION", "FACEMESH_LIPS", "FACEMESH_LEFT_EYE",
         "FACEMESH_LEFT_EYEBROW", "FACEMESH_RIGHT_EYE", "FACEMESH_RIGHT_EYEBROW",
         "FACEMESH_FACE_OVAL", "FACEMESH_LEFT_IRIS", "FACEMESH_RIGHT_IRIS")
edges = set().union(*(tables[name] for name in names))
text = """// Copyright 2021 The MediaPipe Authors. Licensed under Apache-2.0.
// Generated by scripts/generate_face_connections.py from
// https://github.com/google-ai-edge/mediapipe/blob/v0.10.21/mediapipe/python/solutions/face_mesh_connections.py
#pragma once
namespace niji {
inline constexpr unsigned face_connections[][2] = {
"""
text += "".join(f"  {{{a}, {b}}},\n" for a, b in sorted(edges))
text += "};\n} // namespace niji\n"
(root / "src/face_connections.hpp").write_text(text, encoding="utf-8", newline="\n")
